   contains "$queue_help" '--specstory-path PATH' && contains "$queue_help" '--no-plan' && \
   contains "$queue_help" '--message-file PATH'; then
  pass "queue help names every required exact input"
else
  fail "queue help names every required exact input"
fi
# Backticks are literal help text.
# shellcheck disable=SC2016
if contains "$finalizer_help" '--rotation-confirmed' && \
   contains "$finalizer_help" 'ordinary `git commit -F`' && \
   contains "$finalizer_help" 'reconciliation-only'; then
  pass "finalizer help documents one-shot commit and rotation recovery"
