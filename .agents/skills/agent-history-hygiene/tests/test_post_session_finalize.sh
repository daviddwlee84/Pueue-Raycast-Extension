chmod +x "$FAKE_BIN/gitleaks"

cat > "$FAKE_BIN/specstory" <<'SH'
#!/usr/bin/env bash
set -u

write_session() {
  mkdir -p .specstory/history
  if [ "${TEST_INVALID_TRANSCRIPT:-0}" = "1" ]; then
    printf '\377not-a-transcript\n' > .specstory/history/session.md
  else
    printf '%s\n' \
      '<!-- Generated by SpecStory, Markdown v2.1.0 -->' \
      '' \
      '# Post-session test' \
      '' \
      "<!-- Claude Code Session $TEST_UUID (2026-09-01 00:00:00Z) -->" \
      '' \
      '_**Agent (Claude Opus 5 2026-09-01 00:00:01Z)**_' \
      > .specstory/history/session.md
  fi
  if [ -n "${TEST_SESSION_SECRET:-}" ]; then
    printf 'TOKEN=%s\n' "$TEST_SESSION_SECRET" >> .specstory/history/session.md
  fi
  if [ "${TEST_USE_PLAN:-0}" = "1" ]; then
    mkdir -p .claude/plans
    printf '# Exact plan\n' > .claude/plans/exact.md
  fi
  slug=$(printf '%s' "$PWD" | sed 's|[^A-Za-z0-9]|-|g')
  jsonl="$HOME/.claude/projects/$slug/$TEST_UUID.jsonl"
  mkdir -p "$(dirname "$jsonl")"
  python3 - "$jsonl" "$TEST_UUID" "$PWD" <<'PY'
import json, sys
with open(sys.argv[1], "w", encoding="utf-8") as stream:
    stream.write(json.dumps({"type": "user", "sessionId": sys.argv[2], "cwd": sys.argv[3]}) + "\n")
PY
}

queue_once() {
  if [ "${TEST_USE_PLAN:-0}" = "1" ]; then
    "$BASH" "$TEST_QUEUE" --commit --session-id "$TEST_UUID" \
      --specstory-path .specstory/history/session.md \
      --plan .claude/plans/exact.md --message-file message.txt
  else
    "$BASH" "$TEST_QUEUE" --commit --session-id "$TEST_UUID" \
      --specstory-path .specstory/history/session.md \
      --no-plan --message-file message.txt
  fi
}

case "${1:-}" in
  sync)
    printf '%s\n' "$*" >> "$TEST_SYNC_LOG"
    [ "${TEST_SYNC_FAIL:-0}" = "1" ] && exit 41
    exit 0 ;;
  run)
    printf '%s\n' "$*" >> "$TEST_RUN_LOG"
    [ "${2:-}" = claude ] || exit 65
    write_session
    env | LC_ALL=C grep '^AGENT_HISTORY_' | cut -d= -f1 | LC_ALL=C sort > "$TEST_CHILD_ENV_LOG" || :
    printf '%s\n' "$AGENT_HISTORY_REQUEST_PATH" > "$TEST_REQUEST_LOG"
    case "$TEST_MODE" in
      no-request) exit 0 ;;
      queue-once) queue_once; exit $? ;;
      hold)
        queue_once || exit $?
        printf 'ready\n' > "$TEST_READY_FIFO"
        IFS= read -r _release < "$TEST_RELEASE_FIFO"
        exit 0 ;;
      signal-hold)
        trap 'printf "terminated\n" > "$TEST_SIGNAL_LOG"; exit 143' TERM
        queue_once || exit $?
        printf 'ready\n' > "$TEST_READY_FIFO"
        IFS= read -r _release < "$TEST_RELEASE_FIFO"
        exit 0 ;;
      signal-zero-hold)
        trap 'printf "terminated-zero\n" > "$TEST_SIGNAL_LOG"; exit 0' TERM
        queue_once || exit $?
        printf 'ready\n' > "$TEST_READY_FIFO"
        IFS= read -r _release < "$TEST_RELEASE_FIFO"
        exit 0 ;;
      descendant-hold)
        queue_once || exit $?
        python3 - .specstory/history/session.md "$TEST_DESCENDANT_PID_LOG" <<'PY' &
import os, sys, time
with open(sys.argv[1], "ab", buffering=0):
    with open(sys.argv[2], "w", encoding="ascii") as stream:
        stream.write(str(os.getpid()) + "\n")
        stream.flush()
        os.fsync(stream.fileno())
    time.sleep(300)
PY
        while [ ! -s "$TEST_DESCENDANT_PID_LOG" ]; do sleep 0.01; done
        exit 0 ;;
      idempotent-nonzero)
        queue_once || exit $?
        queue_once || exit $?
        exit 37 ;;
      differing-request)
        queue_once || exit $?
        printf 'different body\n' >> message.txt
        queue_once
        exit $? ;;
      unsafe-selector)
        unsafe_path=$'unsafe-selector\nsecond-row.md'
        "$BASH" "$TEST_QUEUE" --commit --session-id "$TEST_UUID" \
          --specstory-path "$unsafe_path" --no-plan --message-file message.txt
        exit $? ;;
      bad-run-mode)
        chmod 0755 "$(dirname "$AGENT_HISTORY_REQUEST_PATH")"
        queue_once
        exit $? ;;
      bad-request-mode)
        queue_once || exit $?
        chmod 0644 "$AGENT_HISTORY_REQUEST_PATH"
        queue_once
        exit $? ;;
      request-symlink)
        target="$(dirname "$AGENT_HISTORY_REQUEST_PATH")/request-target"
        printf '{}\n' > "$target"
        chmod 0600 "$target"
        ln -s request-target "$AGENT_HISTORY_REQUEST_PATH"
        queue_once
        exit $? ;;
      transcript-symlink)
        mv .specstory/history/session.md .specstory/history/session-real.md
        ln -s session-real.md .specstory/history/session.md
        queue_once
        exit $? ;;
      outside-request)
        outside="$PWD/outside/$AGENT_HISTORY_RUN_ID/request.json"
        mkdir -p "$(dirname "$outside")"
        chmod 0700 "$PWD/outside" "$PWD/outside/$AGENT_HISTORY_RUN_ID"
        AGENT_HISTORY_REQUEST_PATH="$outside" queue_once
        exit $? ;;
      unsafe-message)
        printf 'feat: invalid message\rbody\n' > message.txt
        queue_once
        exit $? ;;
      *) exit 66 ;;
    esac ;;
  *) exit 64 ;;
esac
SH
chmod +x "$FAKE_BIN/specstory"

new_context() {
  CONTEXT_COUNT=$((CONTEXT_COUNT + 1))
  REPO="$BASE/repo-$CONTEXT_COUNT"
  HOME_DIR="$BASE/home-$CONTEXT_COUNT"
  OUT_FILE="$BASE/out-$CONTEXT_COUNT"
  ERR_FILE="$BASE/err-$CONTEXT_COUNT"
  REQUEST_LOG="$BASE/request-$CONTEXT_COUNT"
  SYNC_LOG="$BASE/sync-$CONTEXT_COUNT"
  RUN_LOG="$BASE/run-$CONTEXT_COUNT"
  CHILD_ENV_LOG="$BASE/env-$CONTEXT_COUNT"
  READY_FIFO="$BASE/ready-$CONTEXT_COUNT"
  RELEASE_FIFO="$BASE/release-$CONTEXT_COUNT"
  SIGNAL_LOG="$BASE/signal-$CONTEXT_COUNT"
  DESCENDANT_PID_LOG="$BASE/descendant-$CONTEXT_COUNT"
  HOOK_LOG="$BASE/hooks-$CONTEXT_COUNT"
  mkdir -p "$REPO" "$HOME_DIR"
  git -C "$REPO" init -q -b main
  git -C "$REPO" config user.name 'Lifecycle Test'
  git -C "$REPO" config user.email 'lifecycle@example.com'
  printf 'base\n' > "$REPO/feature.txt"
  git -C "$REPO" add feature.txt
  git -C "$REPO" -c core.hooksPath=/dev/null \
    -c user.name=test -c user.email=test@example.com commit -q -m init
  rm -f "$REPO/.git/COMMIT_EDITMSG"
  printf 'feat: finalize recorded session\n\nPreserve the exact post-session review trail.\n' \
    > "$REPO/message.txt"
  TEST_SESSION_SECRET=""
  FAKE_GITLEAKS_FILE=""
  FAKE_GITLEAKS_SECRET=""
  TEST_FAIL_HOOK=""
  TEST_PREPARE_MUTATION=0
  TEST_REMOVE_PROVENANCE=0
  TEST_PRE_COMMIT_READY_FIFO=""
  TEST_PRE_COMMIT_RELEASE_FIFO=""
  rm -f "$HOOK_LOG" "$DESCENDANT_PID_LOG"
  LAST_REQUEST=""
}

stage_feature() {
  printf 'changed\n' >> "$REPO/feature.txt"
  git -C "$REPO" add feature.txt
}

install_native_hooks() {
  local hook hooks_dir="${1:-$REPO/.git/hooks}"
  mkdir -p "$hooks_dir"
  cat > "$hooks_dir/agent-history-test-hook" <<'SH'
#!/usr/bin/env bash
set -u
hook="$(basename "$0")"
printf '%s\t%s\t%s\t%s\t%s\n' \
  "$hook" "$PWD" "${AGENT_HISTORY_SESSION_ID:-}" \
  "${AGENT_HISTORY_SPECSTORY_PATH:-}" \
  "${AGENT_HISTORY_PLAN:-${AGENT_HISTORY_NO_PLAN:-}}" >> "$HOOK_LOG"
if [ "$hook" = pre-commit ] && [ -n "${TEST_PRE_COMMIT_READY_FIFO:-}" ]; then
  printf 'ready\n' > "$TEST_PRE_COMMIT_READY_FIFO"
  IFS= read -r _release < "$TEST_PRE_COMMIT_RELEASE_FIFO"
fi
if [ "$hook" = prepare-commit-msg ]; then
  selector_args=(
    --session-only
    --session-id "$AGENT_HISTORY_SESSION_ID"
    --specstory-path "$AGENT_HISTORY_SPECSTORY_PATH"
  )
  if [ -n "${AGENT_HISTORY_PLAN:-}" ]; then
    selector_args+=(--plan "$AGENT_HISTORY_PLAN")
  else
    selector_args+=(--no-plan)
  fi
  "$BASH" "$TEST_STAGE" "${selector_args[@]}" --check-staged >/dev/null 2>&1 || exit $?
  if [ "${TEST_PREPARE_MUTATION:-0}" = "1" ]; then
    printf 'Hook-Prepared: immediate-owned-mutation\n' >> "$1"
  fi
elif [ "$hook" = commit-msg ]; then
  "$BASH" "$TEST_CHECK_MESSAGE" --agentic --staged --file "$1" >/dev/null 2>&1 || exit $?
  if [ "${TEST_REMOVE_PROVENANCE:-0}" = "1" ]; then
    python3 - "$1" <<'PY'
import os, sys
path = sys.argv[1]
with open(path, "rb") as stream:
    lines = stream.readlines()
with open(path, "wb") as stream:
    stream.writelines(line for line in lines if not line.startswith(b"AI-Assisted-By: "))
os.chmod(path, 0o600)
PY
  fi
fi
if [ "${TEST_FAIL_HOOK:-}" = "$hook" ]; then
  printf '%s\n' 'private hook diagnostic that must stay suppressed' >&2
  exit 42
fi
exit 0
SH
  chmod +x "$hooks_dir/agent-history-test-hook"
  for hook in pre-commit prepare-commit-msg commit-msg post-commit; do
    cp "$hooks_dir/agent-history-test-hook" "$hooks_dir/$hook"
    chmod +x "$hooks_dir/$hook"
  done
}

