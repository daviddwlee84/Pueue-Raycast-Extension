#!/usr/bin/env bash
# Regression tests for the post-session runner, queue, and one-shot finalizer.
# Bash 3.2 compatible (stock macOS).

set -u

TESTS_DIR="$(cd "$(dirname "$0")" && pwd -P)"
SKILL_DIR="$(cd "$TESTS_DIR/.." && pwd -P)"
RUNNER="$SKILL_DIR/scripts/run-specstory-session.sh"
QUEUE="$SKILL_DIR/scripts/queue-agent-commit.sh"
FINALIZER="$SKILL_DIR/scripts/finalize-agent-commit.sh"
STAGE="$SKILL_DIR/scripts/stage-agent-artifacts.sh"
CHECK_MESSAGE="$SKILL_DIR/../git-workflow/scripts/check-commit-msg.sh"
BASE="$(mktemp -d /tmp/test-post-session.XXXXXX)"
BASE="$(cd "$BASE" && pwd -P)"
FAKE_BIN="$BASE/bin"
SYSTEM_PATH="$FAKE_BIN:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin"
UUID="aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa"
PASS_COUNT=0
FAIL_COUNT=0
CONTEXT_COUNT=0
LAST_RC=0
LAST_OUT=""
LAST_ERR=""
LAST_REQUEST=""

trap 'rm -rf "$BASE"' EXIT
mkdir -p "$FAKE_BIN"

printf 'bash-under-test: %s (%s)\n' "$BASH_VERSION" "$BASH"
if [ "$(uname -s)" = "Darwin" ] && [ "${BASH_VERSINFO[0]}" != "3" ]; then
  printf 'error: Darwin compatibility suite must run with /bin/bash 3.x\n' >&2
  exit 1
fi

pass() { PASS_COUNT=$((PASS_COUNT + 1)); printf '  PASS %s\n' "$1"; }
fail() { FAIL_COUNT=$((FAIL_COUNT + 1)); printf '  FAIL %s\n' "$1"; }
contains() { printf '%s\n' "$1" | grep -Fq -- "$2"; }
not_contains() { ! contains "$1" "$2"; }
file_mode() {
  python3 - "$1" <<'PY'
import os, stat, sys
print("%04o" % stat.S_IMODE(os.lstat(sys.argv[1]).st_mode))
PY
}
head_count() { git -C "$1" rev-list --count HEAD; }

cat > "$FAKE_BIN/lsof" <<'SH'
#!/usr/bin/env bash
if [ "${FAKE_LSOF_MODE:-none}" = writer ]; then
  printf '%s\n' p999999 f3 aw
  exit 0
fi
exit 1
SH
chmod +x "$FAKE_BIN/lsof"

cat > "$FAKE_BIN/gitleaks" <<'PY'
#!/usr/bin/env python3
import json
