printf '\n== runner lifecycle and queue boundary ==\n'
new_context
stage_feature
TEST_USE_PLAN=0
TEST_INVALID_TRANSCRIPT=0
TEST_SYNC_FAIL=0
run_runner no-request noauth
first_run_path="$LAST_REQUEST"
run_runner no-request noauth
second_run_path="$LAST_REQUEST"
run_count="$(find "$REPO/.git/agent-history-hygiene/runs" -mindepth 1 -maxdepth 1 -type d | wc -l | tr -d ' ')"
if [ "$LAST_RC" = "0" ] && contains "$LAST_OUT" '"status":"no_request"' && \
   [ ! -e "$first_run_path" ] && [ ! -e "$second_run_path" ] && \
   [ "$first_run_path" != "$second_run_path" ] && [ "$run_count" = "2" ] && \
   [ ! -e "$SYNC_LOG" ]; then
  pass "no-request runs are no-ops with unique private run paths"
else
  fail "no-request runs are no-ops with unique private run paths"
fi

new_context
stage_feature
TEST_USE_PLAN=1
TEST_INVALID_TRANSCRIPT=0
TEST_SYNC_FAIL=0
install_native_hooks
mkfifo "$READY_FIFO" "$RELEASE_FIFO"
: > "$OUT_FILE"; : > "$ERR_FILE"
(
  cd "$REPO" || exit 90
  exec env PATH="$SYSTEM_PATH" HOME="$HOME_DIR" GIT_CONFIG_GLOBAL=/dev/null \
    GIT_CONFIG_SYSTEM=/dev/null AGENT_HISTORY_SECRET_SHOULD_NOT_PASS=hidden \
    AGENT_HISTORY_ALLOW_COMMIT=hidden TEST_QUEUE="$QUEUE" TEST_UUID="$UUID" \
    TEST_MODE=hold TEST_USE_PLAN=1 TEST_INVALID_TRANSCRIPT=0 TEST_SYNC_FAIL=0 \
    TEST_REQUEST_LOG="$REQUEST_LOG" TEST_SYNC_LOG="$SYNC_LOG" TEST_RUN_LOG="$RUN_LOG" \
    TEST_CHILD_ENV_LOG="$CHILD_ENV_LOG" TEST_READY_FIFO="$READY_FIFO" \
    TEST_RELEASE_FIFO="$RELEASE_FIFO" TEST_SIGNAL_LOG="$SIGNAL_LOG" \
    REAL_GIT="$(command -v git)" HOOK_LOG="$HOOK_LOG" TEST_STAGE="$STAGE" \
    TEST_CHECK_MESSAGE="$CHECK_MESSAGE" TEST_FAIL_HOOK='' \
    FAKE_GITLEAKS_FILE='' FAKE_GITLEAKS_SECRET='' \
    /bin/bash "$RUNNER" --protocol-version 1 --provider claude --allow-commit -- --resume "$UUID"
) > "$OUT_FILE" 2> "$ERR_FILE" &
barrier_pid=$!
IFS= read -r barrier_value < "$READY_FIFO"
barrier_request="$(<"$REQUEST_LOG")"
barrier_run_dir="$(dirname "$barrier_request")"
if [ "$barrier_value" = ready ] && [ -f "$barrier_request" ] && \
   [ ! -e "$SYNC_LOG" ] && [ ! -e "$barrier_run_dir/composed-message.txt" ] && \
   [ ! -e "$REPO/.git/LAZYGIT_PENDING_COMMIT" ] && [ ! -e "$HOOK_LOG" ] && \
   [ "$(head_count "$REPO")" = "1" ]; then
  pass "no sync or finalizer occurs before fake SpecStory exits"
else
  fail "no sync or finalizer occurs before fake SpecStory exits"
fi
printf 'release\n' > "$RELEASE_FIFO"
set +e
wait "$barrier_pid"
barrier_rc=$?
set +e
barrier_out="$(<"$OUT_FILE")"
barrier_err="$(<"$ERR_FILE")"
sync_lines="$(wc -l < "$SYNC_LOG" | tr -d ' ')"
child_env_names="$(<"$CHILD_ENV_LOG")"
barrier_names="$(git -C "$REPO" show --format= --name-only HEAD)"
barrier_message="$(git -C "$REPO" show -s --format=%B HEAD)"
hook_lines="$(wc -l < "$HOOK_LOG" | tr -d ' ')"
wrong_hook_cwd="$(cut -f2 "$HOOK_LOG" | grep -Fvx "$REPO" || true)"
if [ "$barrier_rc" = "0" ] && [ "$sync_lines" = "1" ] && \
   grep -Fxq "sync claude -s $UUID --silent" "$SYNC_LOG" && \
   grep -Fxq "run claude --resume $UUID" "$RUN_LOG" && \
   contains "$barrier_out" '"status":"committed"' && \
   contains "$barrier_out" '"commit_attempted":true' && \
   contains "$barrier_err" 'status=committed' && \
   [ "$(head_count "$REPO")" = "2" ]; then
  pass "exit 0 triggers one exact sync and one ordinary commit"
else
  fail "exit 0 triggers one exact sync and one ordinary commit"
