run_runner() {
  mode="$1"
  authorization="$2"
  shift 2
  : > "$OUT_FILE"
  : > "$ERR_FILE"
  rm -f "$REQUEST_LOG" "$SYNC_LOG" "$RUN_LOG" "$CHILD_ENV_LOG" "$SIGNAL_LOG" \
    "$DESCENDANT_PID_LOG"
  set +e
  if [ "$authorization" = allow ]; then
    (cd "$REPO" && runner_env "$mode" /bin/bash "$RUNNER" --protocol-version 1 --provider claude --allow-commit -- "$@") \
      > "$OUT_FILE" 2> "$ERR_FILE"
  else
    (cd "$REPO" && runner_env "$mode" /bin/bash "$RUNNER" --protocol-version 1 --provider claude -- "$@") \
      > "$OUT_FILE" 2> "$ERR_FILE"
  fi
  LAST_RC=$?
  set +e
  LAST_OUT="$(<"$OUT_FILE")"
  LAST_ERR="$(<"$ERR_FILE")"
  if [ -s "$REQUEST_LOG" ]; then LAST_REQUEST="$(<"$REQUEST_LOG")"; else LAST_REQUEST=""; fi
}

run_finalizer() {
  repo="$1"
  request="$2"
  auth_kind="$3"
  auth_value="${4:-}"
  rotation_confirmed="${5:-0}"
  final_out="$BASE/final-out-$CONTEXT_COUNT"
  final_err="$BASE/final-err-$CONTEXT_COUNT"
  if [ "$auth_kind" = allow ]; then
    finalizer_command=(/bin/bash "$FINALIZER" --request "$request" --allow-commit)
  else
    finalizer_command=(/bin/bash "$FINALIZER" --request "$request" --runner-token "$auth_value")
  fi
  [ "$rotation_confirmed" = "1" ] && finalizer_command+=(--rotation-confirmed)
  set +e
  (
    cd "$repo" || exit 90
    exec env PATH="$SYSTEM_PATH" HOME="$HOME_DIR" GIT_CONFIG_GLOBAL=/dev/null \
      GIT_CONFIG_SYSTEM=/dev/null FAKE_GITLEAKS_FILE="${FAKE_GITLEAKS_FILE:-}" \
      FAKE_GITLEAKS_SECRET="${FAKE_GITLEAKS_SECRET:-}" \
      REAL_GIT="${REAL_GIT:-$(command -v git)}" HOOK_LOG="$HOOK_LOG" \
      TEST_STAGE="$STAGE" TEST_CHECK_MESSAGE="$CHECK_MESSAGE" \
      TEST_FAIL_HOOK="${TEST_FAIL_HOOK:-}" \
      TEST_PREPARE_MUTATION="${TEST_PREPARE_MUTATION:-0}" \
      TEST_REMOVE_PROVENANCE="${TEST_REMOVE_PROVENANCE:-0}" \
      TEST_PRE_COMMIT_READY_FIFO="${TEST_PRE_COMMIT_READY_FIFO:-}" \
      TEST_PRE_COMMIT_RELEASE_FIFO="${TEST_PRE_COMMIT_RELEASE_FIFO:-}" \
      "${finalizer_command[@]}"
  ) > "$final_out" 2> "$final_err"
  LAST_RC=$?
  set +e
  LAST_OUT="$(<"$final_out")"
  LAST_ERR="$(<"$final_err")"
  return "$LAST_RC"
}

make_synced_request() {
  new_context
  stage_feature
  TEST_USE_PLAN=0
  TEST_INVALID_TRANSCRIPT=0
  TEST_SYNC_FAIL=0
  run_runner queue-once noauth
  SYNCED_REPO="$REPO"
  SYNCED_REQUEST="$LAST_REQUEST"
}

printf '== post-session public interfaces ==\n'
runner_help="$(/bin/bash "$RUNNER" --help)"
queue_help="$(/bin/bash "$QUEUE" --help)"
finalizer_help="$(/bin/bash "$FINALIZER" --help)"
if contains "$runner_help" 'Usage: run-specstory-session.sh [--allow-commit] claude' && \
   contains "$runner_help" '--provider claude' && contains "$runner_help" 'foreground TTY' && \
   contains "$runner_help" '22      child process group remained live'; then
  pass "runner help is explicit and noninteractive-friendly"
else
  fail "runner help is explicit and noninteractive-friendly"
